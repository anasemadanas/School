# ------------------------------------------------------------------ helpers
def alias(full: str) -> str:
    return full.replace(".", "_")


def module_tables(model: dict[str, Table], mod: str) -> list[Table]:
    out = []
    for pattern in MODULES[mod]["tables"]:
        if pattern.endswith(".*"):
            schema = pattern[:-2]
            out += sorted((t for t in model.values() if t.schema == schema), key=lambda t: t.name)
        else:
            out.append(model[pattern])
    return out


def module_of(full: str) -> str:
    for mod in MODULES:
        for pattern in MODULES[mod]["tables"]:
            if pattern == full or (pattern.endswith(".*") and full.split(".")[0] == pattern[:-2]):
                return mod
    raise KeyError(full)


def singular(name: str) -> str:
    if name.endswith("Series") or name.endswith("History"):
        return name
    if name.endswith("ies"):
        return name[:-3] + "y"
    if name.endswith(("sses", "uses", "ches", "shes", "xes")):
        return name[:-2]
    if name.endswith("s"):
        return name[:-1]
    return name


def business_name(t: Table) -> str:
    return re.sub(r"(?<=[a-z])(?=[A-Z])", " ", singular(t.name))


def fk_is_unique(t: Table, cols: list[str]) -> bool:
    keys = ([t.pk.columns] if t.pk else []) + [u.columns for u in t.uqs] + \
           [i.columns for i in t.indexes if i.unique and not i.filter]
    return any(sorted(k) == sorted(cols) for k in keys)


def crowfoot(t: Table, fk) -> str:
    nullable = any(t.column(c).nullable for c in fk.columns)
    parent = "|o" if nullable else "||"
    child = "o|" if fk_is_unique(t, fk.columns) else "o{"
    return f"{parent}--{child}"


def verb(fk, child: Table) -> str:
    if fk.name in VERBS:
        return VERBS[fk.name]
    if fk.ref_table in LOOKUPS:
        return "classifies"
    if fk.ref_table.endswith("AcademicYears"):
        return "scopes"
    if fk.ref_table.endswith("Branches"):
        return "hosts"
    return "has"


def stereotypes(t: Table) -> str:
    s = []
    if t.full_name in LOOKUPS:
        s.append("<<lookup>>")
    if t.temporal_history:
        s.append("<<temporal>>")
    if t.history_of:
        s.append("<<history>>")
    return " ".join(s)


def header(title: str, include: str) -> list[str]:
    return ["@startuml", GENERATED_BANNER, f"!include {include}", f"title {title}", ""]


# --------------------------------------------------------- physical level
def phys_column_line(t: Table, c) -> str:
    tags = []
    if t.pk and c.name in t.pk.columns:
        tags.append("«PK»")
    if any(c.name in fk.columns for fk in t.fks):
        tags.append("«FK»")
    if c.identity:
        tags.append(f"«{c.identity}»")
    if c.generated:
        tags.append(f"«{c.generated}»")
    if c.hidden:
        tags.append("«HIDDEN»")
    star = "* " if not c.nullable else ""
    return f"  {star}{c.name} : {c.type} {'NULL' if c.nullable else 'NOT NULL'}{(' ' + ' '.join(tags)) if tags else ''}"


def shorten(text: str, n: int = 90) -> str:
    text = re.sub(r"\s+", " ", text)
    return text if len(text) <= n else text[: n - 1] + "…"


def phys_entity(t: Table) -> list[str]:
    lines = [f'entity "{t.full_name}" as {alias(t.full_name)} {stereotypes(t)}'.rstrip() + " {"]
    for c in t.columns:
        lines.append(phys_column_line(t, c))
    lines.append("  --")
    if t.pk:
        lines.append(f"  PK {t.pk.name} ({', '.join(t.pk.columns)})")
    for u in t.uqs:
        lines.append(f"  UQ {u.name} ({', '.join(u.columns)})")
    for fk in t.fks:
        extra = " ON DELETE CASCADE" if fk.on_delete == "CASCADE" else ""
        lines.append(f"  FK {fk.name} ({', '.join(fk.columns)}) -> {fk.ref_table} ({', '.join(fk.ref_columns)}){extra}")
    for ck in t.cks:
        lines.append(f"  CK {ck.name} : {shorten(ck.definition)}")
    for df in t.dfs:
        lines.append(f"  DF {df.name} : {df.column} = {df.definition}")
    for ix in t.indexes:
        parts = [f"  IX {ix.name} ({', '.join(ix.columns)})"]
        if ix.includes:
            parts.append(f"INCLUDE ({', '.join(ix.includes)})")
        if ix.unique:
            parts.append("UNIQUE")
        if ix.clustered:
            parts.append("CLUSTERED")
        if ix.filter:
            parts.append(f"WHERE {ix.filter}")
        lines.append(" ".join(parts))
    if t.temporal_history:
        lines.append(f"  TEMPORAL SYSTEM_VERSIONING = ON, HISTORY_TABLE = {t.temporal_history}")
    if t.history_of:
        lines.append(f"  HISTORY OF {t.history_of} (maintained by SQL Server)")
    lines.append("}")
    return lines


def external_stub(full: str, level: str) -> list[str]:
    name = full if level != "conceptual" else full.split(".")[1]
    return [f'entity "{name}" as {alias(full)} <<external>> {{', f"  see module: {module_of(full)}", "}"]


def edges(tables: list[Table], model: dict[str, Table], level: str, keep_external: bool = True) -> tuple[list[str], set[str]]:
    names = {t.full_name for t in tables}
    out, external = [], set()
    for t in tables:
        for fk in t.fks:
            if fk.ref_table not in names:
                if not keep_external:
                    continue
                external.add(fk.ref_table)
            label = verb(fk, t) if level == "conceptual" else fk.name
            out.append(f"{alias(fk.ref_table)} {crowfoot(t, fk)} {alias(t.full_name)} : {label}")
    return out, external


def write(path: Path, lines: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def gen_physical(model: dict[str, Table]) -> None:
    for mod, cfg in MODULES.items():
        tables = module_tables(model, mod)
        lines = header(f"Physical model - {cfg['title']}  (SQL Server 2022)", "../../_style.iuml")
        for t in tables:
            lines += phys_entity(t) + [""]
        rel, ext = edges(tables, model, "physical")
        for e in sorted(ext):
            lines += external_stub(e, "physical") + [""]
        lines += rel + ["", "legend right", "  «PK» primary key  «FK» foreign key  * NOT NULL", "  PK/UQ/FK/CK/DF/IX = constraint and index names as deployed",
                        "  grey <<external>> = table owned by another module", "endlegend", "@enduml"]
        write(DIAGRAMS / "physical" / "modules" / f"{mod}.puml", lines)

    lines = header("Physical model - MASTER OVERVIEW (keys and relationships only; full detail in modules/)", "../_style.iuml")
    lines += ["skinparam linetype ortho", ""]
    for mod, cfg in MODULES.items():
        lines.append(f'package "{mod}" {{')
        for t in module_tables(model, mod):
            lines.append(f'  entity "{t.full_name}" as {alias(t.full_name)} {stereotypes(t)}'.rstrip() + " {")
            key_cols = [c for c in t.columns if (t.pk and c.name in t.pk.columns) or any(c.name in fk.columns for fk in t.fks)]
            for c in key_cols:
                lines.append("  " + phys_column_line(t, c))
            lines.append("  }")
        lines.append("}")
    rel, _ = edges(list(model.values()), model, "physical")
    lines += [""] + rel + ["", "note as N1", "  OVERVIEW ONLY: shows every table with its key columns",
                           "  (PK / FK) and every foreign-key relationship. Data columns,", "  CHECK, DEFAULT, UNIQUE constraints and indexes are in",
                           "  diagrams/physical/modules/*.puml.", "end note", "@enduml"]
    write(DIAGRAMS / "physical" / "master_physical.puml", lines)


# ---------------------------------------------------------- logical level
AUDIT_COLS = {"CreatedAt", "CreatedBy", "UpdatedAt", "UpdatedBy"}
PHYSICAL_ONLY = {"RowVer", "SysStartTime", "SysEndTime"}


def domain(t: Table, c) -> str:
    is_key = (t.pk and c.name in t.pk.columns) or any(c.name in fk.columns for fk in t.fks)
    ty = c.type
    if is_key and ty in ("INT", "BIGINT"):
        return "Identifier"
    if ty.startswith("NVARCHAR(MAX)"):
        return "LongText (JSON)"
    if ty.startswith("NVARCHAR") or ty.startswith("NCHAR"):
        return f"Text({ty[ty.index('(') + 1:-1]})"
    if ty == "DECIMAL(19,4)":
        return "Money"
    if ty == "DECIMAL(7,4)":
        return "Percentage"
    if ty.startswith("DECIMAL"):
        return "Decimal"
    if ty == "DATE":
        return "Date"
    if ty.startswith("DATETIME2"):
        return "Timestamp"
    if ty.startswith("TIME"):
        return "Time"
    if ty == "BIT":
        return "Flag"
    if ty in ("TINYINT", "SMALLINT", "INT", "BIGINT"):
        return "Integer"
    if ty.startswith("VARBINARY"):
        return "Binary"
    return ty


def logical_entity(t: Table) -> list[str]:
    enums = enum_values(t)
    ak_of: dict[str, list[str]] = {}
    # Superkeys of the PK (helper keys for composite FKs) are physical artefacts, not alternate keys.
    real_aks = [u for u in t.uqs if not (t.pk and set(t.pk.columns) <= set(u.columns))]
    for n, u in enumerate(real_aks, 1):
        for c in u.columns:
            ak_of.setdefault(c, []).append(f"AK{n}")
    lines = [f'entity "{t.name}" as {alias(t.full_name)} {stereotypes(t)}'.rstrip() + " {"]
    pk_cols = t.pk.columns if t.pk else []
    for c in [c for c in t.columns if c.name in pk_cols]:
        tags = ["«PK»"] + (["«FK»"] if any(c.name in fk.columns for fk in t.fks) else [])
        lines.append(f"  * {c.name} : {domain(t, c)} {' '.join(tags)}")
    lines.append("  --")
    audited = False
    for c in t.columns:
        if c.name in pk_cols or c.name in PHYSICAL_ONLY:
            continue
        if c.name in AUDIT_COLS:
            audited = True
            continue
        tags = []
        if any(c.name in fk.columns for fk in t.fks):
            tags.append("«FK»")
        tags += [f"«{a}»" for a in ak_of.get(c.name, [])]
        dom = domain(t, c)
        if c.name in enums:
            dom += " {" + " | ".join(enums[c.name]) + "}"
        star = "* " if not c.nullable else ""
        lines.append(f"  {star}{c.name} : {dom}{(' ' + ' '.join(tags)) if tags else ''}")
    if audited:
        lines += ["  ..", "  «audited» created/updated at + by"]
    if t.temporal_history:
        lines.append("  «history kept» every version retained")
    lines.append("}")
    return lines


def gen_logical(model: dict[str, Table]) -> None:
    for mod, cfg in MODULES.items():
        tables = [t for t in module_tables(model, mod) if not t.history_of]
        lines = header(f"Logical model - {cfg['title']}", "../../_style.iuml")
        for t in tables:
            lines += logical_entity(t) + [""]
        rel, ext = edges(tables, model, "logical")
        for e in sorted(ext):
            lines += external_stub(e, "logical") + [""]
        lines += rel + ["", f"note as Rules\n{LOGICAL_NOTES[mod]}\nend note", "",
                        "legend right", "  Domains: Identifier, Text(n), Integer, Decimal, Money, Percentage,",
                        "  Date, Time, Timestamp, Flag, Binary.  * = mandatory", "  «PK» primary key  «FK» foreign key  «AKn» alternate key n",
                        "  {a | b} = allowed values.  Audit columns and physical-only", "  columns (row version, period columns) are summarised.",
                        "endlegend", "@enduml"]
        write(DIAGRAMS / "logical" / "modules" / f"{mod}.puml", lines)

    lines = header("Logical model - MASTER (entities, identifiers and relationships; attributes in modules/)", "../_style.iuml")
    lines += ["skinparam linetype ortho", ""]
    for mod in MODULES:
        lines.append(f'package "{mod}" {{')
        for t in module_tables(model, mod):
            if t.history_of:
                continue
            lines.append(f'  entity "{t.name}" as {alias(t.full_name)} {stereotypes(t)}'.rstrip() + " {")
            for c in t.columns:
                if t.pk and c.name in t.pk.columns:
                    lines.append(f"    * {c.name} : Identifier «PK»")
            lines.append("  }")
        lines.append("}")
    rel, _ = edges([t for t in model.values() if not t.history_of], model, "logical")
    lines += [""] + rel + ["@enduml"]
    write(DIAGRAMS / "logical" / "master_logical.puml", lines)


# -------------------------------------------------------- conceptual level
def gen_conceptual(model: dict[str, Table]) -> None:
    for mod, cfg in MODULES.items():
        tables = [t for t in module_tables(model, mod) if not t.history_of]
        lines = header(f"Conceptual model - {cfg['title']}", "../../_style.iuml")
        lines.append("hide members")
        for t in tables:
            lines.append(f'entity "{business_name(t)}" as {alias(t.full_name)} {stereotypes(t)}'.rstrip())
        rel, ext = edges(tables, model, "conceptual")
        for e in sorted(ext):
            lines.append(f'entity "{business_name(model[e])}" as {alias(e)} <<external>>')
        lines += [""] + rel + ["", "legend right", "  Crow's foot: || exactly one, |o zero or one, o{ zero or many, o| zero or one (child side)",
                               "  <<lookup>> reference list   <<temporal>> full history kept   <<external>> other module", "endlegend", "@enduml"]
        write(DIAGRAMS / "conceptual" / "modules" / f"{mod}.puml", lines)

    # Master: every entity grouped by module, cross-module relationships,
    # and the empty reserved schemas.
    lines = header("Conceptual model - MASTER (all 15 schemas; 5 are empty, reserved for future expansion)", "../_style.iuml")
    lines += ["hide members", ""]
    all_tables = [t for t in model.values() if not t.history_of]
    for mod, cfg in MODULES.items():
        lines.append(f'package "{mod}" {{')
        for t in module_tables(model, mod):
            if not t.history_of:
                lines.append(f'  entity "{business_name(t)}" as {alias(t.full_name)} {stereotypes(t)}'.rstrip())
        lines.append("}")
    for mod in RESERVED_SCHEMAS:
        lines.append(f'package "{mod} (reserved - empty schema)" as R_{mod} <<reserved>> {{')
        lines.append("}")
    lines.append("")
    for t in all_tables:
        for fk in t.fks:
            if module_of(fk.ref_table) != module_of(t.full_name) and fk.ref_table not in LOOKUPS \
                    and not fk.ref_table.startswith("organization.Branches") and not fk.ref_table.endswith("AcademicYears"):
                lines.append(f"{alias(fk.ref_table)} {crowfoot(t, fk)} {alias(t.full_name)} : {verb(fk, t)}")
    lines += ["", "note as N1", "  Cross-module relationships only (lookups, branch and academic-year",
              "  scoping omitted for readability). Every relationship with its",
              "  cardinality is in diagrams/conceptual/modules/*.puml.",
              "  Dashed packages: empty schemas reserved for future expansion",
              "  (no tables); see docs/FUTURE_EXPANSION.md.", "end note", "@enduml"]
    write(DIAGRAMS / "conceptual" / "master_conceptual.puml", lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--catalog", help="ODBC connection string of a deployed database (default: parse sql/)")
    args = ap.parse_args()
    model = load_from_catalog(args.catalog) if args.catalog else load_from_ddl()
    gen_physical(model)
    gen_logical(model)
    gen_conceptual(model)
    n_tables = len(model)
    n_fk = sum(len(t.fks) for t in model.values())
    print(f"Generated diagrams for {n_tables} tables and {n_fk} relationships "
          f"from {'catalog' if args.catalog else 'sql/ DDL scripts'}.")
    return 0


